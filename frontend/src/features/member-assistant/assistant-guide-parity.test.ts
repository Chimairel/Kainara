import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { expect, it } from 'vitest';

it('ships the same reviewed guide and matcher to the browser and the server', () => {
  const canonical = readFileSync(resolve('../backend/src/domain/member-assistant-information.ts'), 'utf8').replaceAll('\r\n', '\n');
  const generated = readFileSync(resolve('src/features/member-assistant/assistant-information.generated.ts'), 'utf8').replaceAll('\r\n', '\n');
  expect(generated).toBe('// Generated by scripts/sync-assistant-guide.mjs. Edit the backend guide, then regenerate.\n' + canonical);
});
