import { readFileSync, writeFileSync } from 'node:fs';

// Keep each independently deployed app self-contained, with one reviewed source.
const source = new URL('../backend/src/domain/member-assistant-information.ts', import.meta.url);
const destination = new URL('../frontend/src/features/member-assistant/assistant-information.generated.ts', import.meta.url);
const contents = '// Generated by scripts/sync-assistant-guide.mjs. Edit the backend guide, then regenerate.\n'
  + readFileSync(source, 'utf8').replaceAll('\r\n', '\n');
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8').replaceAll('\r\n', '\n') !== contents) throw new Error('Nara guides differ. Run node scripts/sync-assistant-guide.mjs.');
} else {
  writeFileSync(destination, contents);
}
